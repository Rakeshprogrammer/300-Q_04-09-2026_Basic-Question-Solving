//Q1- Take a number and print whether it's positive, negative, or zero
public class Main1{
    public static void main(String args[]){
        int number = 10;
        if(number>0){
            System.out.println("Positive");
        }
        else if(number<0){
            System.out.println("Negative");
        }else{
            System.out.println("Zero");
        }
    }
}